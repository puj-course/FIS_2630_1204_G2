-- Crea `categorias` y `precios_producto`, migra las categorias de texto libre
-- y agrega las claves foraneas e indices que pide el criterio de aceptacion.

CREATE TABLE IF NOT EXISTS categorias (
    categoria_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre                VARCHAR(100) NOT NULL,
    descripcion           VARCHAR(300),
    orden_presentacion    INTEGER DEFAULT 0 NOT NULL,
    estado                VARCHAR(10) DEFAULT 'ACTIVO' NOT NULL,
    fecha_creacion        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_actualizacion   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_categorias PRIMARY KEY (categoria_id),
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre),
    CONSTRAINT ck_categoria_orden CHECK (orden_presentacion >= 0),
    CONSTRAINT ck_categoria_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE INDEX IF NOT EXISTS ix_categorias_orden
    ON categorias (orden_presentacion, nombre);

-- Convierte en filas las categorias que hoy son texto en productos.
-- En SQL dinamico para que el script se pueda volver a ejecutar despues de que
-- la columna de texto haya sido eliminada.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_name = 'productos' AND column_name = 'categoria'
    ) THEN
        EXECUTE $sql$
            INSERT INTO categorias (nombre)
            SELECT DISTINCT btrim(categoria)
              FROM productos
             WHERE categoria IS NOT NULL AND btrim(categoria) <> ''
            ON CONFLICT (nombre) DO NOTHING
        $sql$;
    END IF;
END
$$;

