CREATE INDEX IF NOT EXISTS ix_productos_categoria
    ON productos (categoria_id, nombre);

CREATE INDEX IF NOT EXISTS ix_productos_estado
    ON productos (estado);

-- Historial de precios. productos.precio_venta sigue siendo el precio vigente.
CREATE TABLE IF NOT EXISTS precios_producto (
    precio_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    producto_id    BIGINT NOT NULL,
    precio         NUMERIC(12,2) NOT NULL,
    fecha_inicio   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_fin      TIMESTAMP,
    motivo         VARCHAR(255),

    CONSTRAINT pk_precios_producto PRIMARY KEY (precio_id),
    CONSTRAINT fk_precios_producto FOREIGN KEY (producto_id) REFERENCES productos(producto_id),
    CONSTRAINT ck_precio_valor CHECK (precio > 0),
    CONSTRAINT ck_precio_vigencia CHECK (fecha_fin IS NULL OR fecha_fin > fecha_inicio)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_precios_producto_vigente
    ON precios_producto (producto_id) WHERE fecha_fin IS NULL;

CREATE INDEX IF NOT EXISTS ix_precios_producto_historial
    ON precios_producto (producto_id, fecha_inicio);

-- Deja registrado el precio actual como el primer tramo vigente.
INSERT INTO precios_producto (producto_id, precio, motivo)
SELECT p.producto_id, p.precio_venta, 'Precio inicial migrado'
  FROM productos p
 WHERE NOT EXISTS (
        SELECT 1 FROM precios_producto pp
         WHERE pp.producto_id = p.producto_id AND pp.fecha_fin IS NULL
 );
