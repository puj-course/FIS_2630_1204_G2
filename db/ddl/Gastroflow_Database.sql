-- ===== ddl/productos =====
CREATE TABLE productos (
                           producto_id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
                           codigo                VARCHAR(30) NOT NULL,
                           nombre                VARCHAR(120) NOT NULL,
                           descripcion           VARCHAR(500),
                           categoria_id          BIGINT NOT NULL,
                           precio_venta          NUMERIC(12,2) NOT NULL,
                           costo                 NUMERIC(12,2) DEFAULT 0 NOT NULL,
                           stock_minimo          NUMERIC(12,4) DEFAULT 0 NOT NULL,
                           stock_maximo          NUMERIC(12,4),
                           estado                VARCHAR(15) DEFAULT 'DISPONIBLE' NOT NULL,
                           fecha_creacion        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                           fecha_actualizacion   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                           CONSTRAINT pk_productos PRIMARY KEY (producto_id),
                           CONSTRAINT uq_productos_codigo UNIQUE (codigo),
                           CONSTRAINT uq_productos_nombre UNIQUE (nombre),
                           CONSTRAINT fk_productos_categoria FOREIGN KEY (categoria_id)
                               REFERENCES categorias(categoria_id),
                           CONSTRAINT ck_producto_precio CHECK (precio_venta > 0),
                           CONSTRAINT ck_producto_costo CHECK (costo >= 0),
                           CONSTRAINT ck_producto_stock_minimo CHECK (stock_minimo >= 0),
                           CONSTRAINT ck_producto_stock_maximo CHECK (
                               stock_maximo IS NULL OR stock_maximo >= stock_minimo),
                           CONSTRAINT ck_producto_estado CHECK (
                               estado IN ('DISPONIBLE', 'AGOTADO', 'INACTIVO'))
);

CREATE INDEX ix_productos_categoria ON productos (categoria_id, nombre);
CREATE INDEX ix_productos_estado ON productos (estado);

-- ===== ddl/ingredientes =====
CREATE TABLE ingredientes (
                              ingrediente_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
                              nombre                VARCHAR(100) NOT NULL,
                              descripcion           VARCHAR(300),
                              unidad_medida	      VARCHAR(30) NOT NULL,
                              costo_unitario        NUMERIC(12,2) DEFAULT 0 NOT NULL,
                              stock_actual          NUMERIC(12,4) DEFAULT 0 NOT NULL,
                              stock_minimo          NUMERIC(12,4) DEFAULT 0 NOT NULL,
                              stock_maximo          NUMERIC(12,4),
                              proveedor             VARCHAR(150),
                              estado                VARCHAR(10) DEFAULT 'ACTIVO' NOT NULL,
                              fecha_creacion        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                              fecha_actualizacion   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                              CONSTRAINT pk_ingredientes PRIMARY KEY (ingrediente_id),
                              CONSTRAINT ck_ingredientes_costo_positivo CHECK (costo_unitario >= 0),
                              CONSTRAINT ck_ingredientes_stock_actual_no_negativo CHECK (stock_actual >= 0),
                              CONSTRAINT ck_ingredientes_stock_minimo_no_negativo CHECK (stock_minimo >= 0),
                              CONSTRAINT ck_ingredientes_stock_maximo_valido CHECK (stock_maximo IS NULL OR stock_maximo >= stock_minimo),
                              CONSTRAINT ck_ingredientes_estado_valido CHECK (UPPER(estado) IN ('ACTIVO', 'INACTIVO'))
);

-- ===== producto_ingrediente (tabla unificada de recetas) =====
CREATE TABLE producto_ingrediente (
                                      producto_id         BIGINT NOT NULL,
                                      ingrediente_id      BIGINT NOT NULL,
                                      cantidad_necesaria  NUMERIC(10,2) NOT NULL,
                                      CONSTRAINT pk_producto_ingrediente PRIMARY KEY (producto_id, ingrediente_id),
                                      CONSTRAINT fk_producto_ingrediente_producto FOREIGN KEY (producto_id)
                                          REFERENCES productos(producto_id) ON DELETE CASCADE,
                                      CONSTRAINT fk_producto_ingrediente_ingrediente FOREIGN KEY (ingrediente_id)
                                          REFERENCES ingredientes(ingrediente_id) ON DELETE CASCADE,
                                      CONSTRAINT ck_producto_ingrediente_cantidad CHECK (cantidad_necesaria > 0)
);

CREATE INDEX ix_producto_ingrediente_ingrediente
    ON producto_ingrediente (ingrediente_id);


