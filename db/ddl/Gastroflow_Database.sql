-- ===== ddl/roles =====
CREATE TABLE roles (
                       id_rol      INTEGER GENERATED ALWAYS AS IDENTITY,
                       nombre_rol  VARCHAR(50) NOT NULL,
                       descripcion VARCHAR(255),
                       CONSTRAINT pk_roles PRIMARY KEY (id_rol),
                       CONSTRAINT uk_roles_nombre UNIQUE (nombre_rol)
);

-- ===== ddl/tipos_documento =====
CREATE TABLE tipos_documento (
                                 id_tipo_documento INTEGER GENERATED ALWAYS AS IDENTITY,
                                 codigo            VARCHAR(10) NOT NULL,
                                 nombre            VARCHAR(50) NOT NULL,
                                 CONSTRAINT pk_tipos_documento PRIMARY KEY (id_tipo_documento),
                                 CONSTRAINT uk_tipos_doc_codigo UNIQUE (codigo)
);

-- ===== ddl/zonas =====
CREATE TABLE zonas (
                       id_zona     INTEGER GENERATED ALWAYS AS IDENTITY,
                       nombre_zona VARCHAR(50) NOT NULL,
                       descripcion VARCHAR(255),
                       is_active   SMALLINT DEFAULT 1 NOT NULL,
                       CONSTRAINT pk_zonas PRIMARY KEY (id_zona),
                       CONSTRAINT uk_zonas_nombre UNIQUE (nombre_zona),
                       CONSTRAINT chk_zonas_active CHECK (is_active IN (0, 1))
);

-- ===== ddl/estados_mesa =====
CREATE TABLE estados_mesa (
                              id_estado_mesa INTEGER GENERATED ALWAYS AS IDENTITY,
                              codigo_estado  VARCHAR(20) NOT NULL,
                              descripcion    VARCHAR(100),
                              CONSTRAINT pk_estados_mesa PRIMARY KEY (id_estado_mesa),
                              CONSTRAINT uk_estados_mesa_codigo UNIQUE (codigo_estado)
);

-- ===== categorias  =============
CREATE TABLE categorias (
                            categoria_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
                            nombre                VARCHAR(100) NOT NULL,
                            descripcion           VARCHAR(300),
                            orden_visual          INTEGER DEFAULT 0 NOT NULL,
                            estado                VARCHAR(10) DEFAULT 'ACTIVO' NOT NULL,
                            fecha_creacion        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                            fecha_actualizacion   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                            CONSTRAINT pk_categorias PRIMARY KEY (categoria_id),
                            CONSTRAINT uq_categorias_nombre UNIQUE (nombre),
                            CONSTRAINT ck_categoria_orden CHECK (orden_visual >= 0),
                            CONSTRAINT ck_categoria_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE INDEX ix_categorias_orden
    ON categorias (orden_visual, nombre);


