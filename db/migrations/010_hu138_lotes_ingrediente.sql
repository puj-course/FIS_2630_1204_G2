-- HU-138: crear lotes por ingrediente y migrar los datos heredados.
-- No se eliminan ni modifican las columnas legacy de ingredientes.
BEGIN;

CREATE TABLE IF NOT EXISTS lote_ingrediente (
    lote_ingrediente_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ingrediente_id      BIGINT NOT NULL,
    codigo_lote         VARCHAR(50) NOT NULL,
    cantidad            NUMERIC(12,4) NOT NULL DEFAULT 0,
    fecha_vencimiento   DATE,
    fecha_ingreso       DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_lote_ingrediente
        PRIMARY KEY (lote_ingrediente_id),
    CONSTRAINT fk_lote_ingrediente_ingrediente
        FOREIGN KEY (ingrediente_id)
        REFERENCES ingredientes(ingrediente_id),
    CONSTRAINT uq_lote_ingrediente_insumo_codigo
        UNIQUE (ingrediente_id, codigo_lote),
    CONSTRAINT ck_lote_ingrediente_cantidad
        CHECK (cantidad >= 0)
);

CREATE INDEX IF NOT EXISTS ix_lote_ingrediente_fecha_vencimiento
    ON lote_ingrediente (fecha_vencimiento);

-- Se conserva un registro por ingrediente con datos heredados relevantes.
-- Si no había código de lote pero sí stock o vencimiento, se usa un código
-- identificable LEGACY-<ingrediente_id>. El stock agregado pasa a cantidad.
-- ON CONFLICT DO NOTHING evita sobrescribir lotes que ya se hayan gestionado.
INSERT INTO lote_ingrediente (
    ingrediente_id,
    codigo_lote,
    cantidad,
    fecha_vencimiento,
    fecha_ingreso
)
SELECT
    i.ingrediente_id,
    COALESCE(NULLIF(BTRIM(i.lote), ''), 'LEGACY-' || i.ingrediente_id::TEXT),
    i.stock_actual,
    i.fecha_vencimiento,
    i.fecha_creacion::DATE
FROM ingredientes i
WHERE NULLIF(BTRIM(i.lote), '') IS NOT NULL
   OR i.fecha_vencimiento IS NOT NULL
   OR i.stock_actual > 0
ON CONFLICT (ingrediente_id, codigo_lote) DO NOTHING;

COMMIT;
