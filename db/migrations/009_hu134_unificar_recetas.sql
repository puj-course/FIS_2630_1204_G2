-- HU-134: Unificar recetas en plato_insumo.
-- productos.ingredientes se conserva temporalmente por compatibilidad.
-- Los productos INACTIVO no se modifican.

BEGIN;

-- 1. Tabla de auditoría.
CREATE TABLE IF NOT EXISTS auditoria_recetas_hu134 (
                                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                       producto_id BIGINT NOT NULL,
                                                       tipo_evento VARCHAR(40) NOT NULL,
    detalle JSONB NOT NULL,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_auditoria_recetas_hu134
    UNIQUE (producto_id, tipo_evento, detalle)
    );

-- 2. Registrar recetas JSONB con una estructura incorrecta.
INSERT INTO auditoria_recetas_hu134 (
    producto_id,
    tipo_evento,
    detalle
)
SELECT
    p.producto_id,
    'RECETA_INVALIDA',
    jsonb_build_object(
            'ingredientes', p.ingredientes,
            'motivo', 'La receta JSONB no tiene formato de arreglo'
    )
FROM productos p
WHERE p.estado <> 'INACTIVO'
  AND p.ingredientes IS NOT NULL
  AND jsonb_typeof(p.ingredientes) <> 'array'
    ON CONFLICT (producto_id, tipo_evento, detalle) DO NOTHING;

-- 3. Convertir las recetas JSONB a filas validadas.
CREATE TEMP TABLE hu134_json_validado
ON COMMIT DROP
AS
SELECT
    p.producto_id,
    e.valor AS elemento,
    CASE
        WHEN e.valor ->> 'ingrediente_id' ~ '^[0-9]+$'
        AND length(e.valor ->> 'ingrediente_id') <= 18
    THEN (e.valor ->> 'ingrediente_id')::BIGINT
        ELSE NULL
END AS ingrediente_id,
    CASE
        WHEN e.valor ->> 'cantidad' ~ '^[0-9]+([.][0-9]+)?$'
         AND length(e.valor ->> 'cantidad') <= 30
        THEN (e.valor ->> 'cantidad')::NUMERIC
        ELSE NULL
END AS cantidad
FROM productos p
CROSS JOIN LATERAL jsonb_array_elements(
    CASE
        WHEN jsonb_typeof(p.ingredientes) = 'array'
        THEN p.ingredientes
        ELSE '[]'::JSONB
    END
) AS e(valor)
WHERE p.estado <> 'INACTIVO';

-- 4. Auditar datos inválidos y referencias inexistentes.
INSERT INTO auditoria_recetas_hu134 (
    producto_id,
    tipo_evento,
    detalle
)
SELECT
    v.producto_id,
    CASE
        WHEN v.ingrediente_id IS NOT NULL
            AND i.ingrediente_id IS NULL
            THEN 'INGREDIENTE_INEXISTENTE'
        ELSE 'RECETA_INVALIDA'
        END,
    jsonb_build_object(
            'elemento', v.elemento,
            'ingrediente_id', v.ingrediente_id,
            'cantidad', v.cantidad,
            'motivo',
            CASE
                WHEN v.ingrediente_id IS NULL
                    THEN 'ID de ingrediente inválido'
                WHEN v.cantidad IS NULL OR v.cantidad <= 0
                    THEN 'Cantidad inválida'
                WHEN i.ingrediente_id IS NULL
                    THEN 'Ingrediente inexistente'
                END
    )
FROM hu134_json_validado v
         LEFT JOIN ingredientes i
                   ON i.ingrediente_id = v.ingrediente_id
WHERE v.ingrediente_id IS NULL
   OR v.cantidad IS NULL
   OR v.cantidad <= 0
   OR i.ingrediente_id IS NULL
    ON CONFLICT (producto_id, tipo_evento, detalle) DO NOTHING;

-- 5. Seleccionar recetas completas y válidas.
-- Si un elemento de la receta es inválido, se descarta la receta
-- completa de ese producto; no se migra parcialmente.
CREATE TEMP TABLE hu134_recetas_validas
ON COMMIT DROP
AS
SELECT
    v.producto_id,
    v.ingrediente_id,
    SUM(v.cantidad) AS cantidad
FROM hu134_json_validado v
         JOIN ingredientes i
              ON i.ingrediente_id = v.ingrediente_id
WHERE v.ingrediente_id IS NOT NULL
  AND v.cantidad IS NOT NULL
  AND v.cantidad > 0
  AND NOT EXISTS (
    SELECT 1
    FROM hu134_json_validado invalido
             LEFT JOIN ingredientes ix
                       ON ix.ingrediente_id = invalido.ingrediente_id
    WHERE invalido.producto_id = v.producto_id
      AND (
        invalido.ingrediente_id IS NULL
            OR invalido.cantidad IS NULL
            OR invalido.cantidad <= 0
            OR ix.ingrediente_id IS NULL
        )
)
GROUP BY v.producto_id, v.ingrediente_id;

-- 6. Auditar discrepancias cuando ambas fuentes tienen receta.
WITH normalizada AS (
    SELECT
        pi.plato_id AS producto_id,
        pi.insumo_id AS ingrediente_id,
        SUM(pi.cantidad_necesaria) AS cantidad
    FROM plato_insumo pi
             JOIN productos p
                  ON p.producto_id = pi.plato_id
    WHERE p.estado <> 'INACTIVO'
    GROUP BY pi.plato_id, pi.insumo_id
),
     diferencias AS (
         SELECT
             COALESCE(j.producto_id, n.producto_id) AS producto_id,
             COALESCE(j.ingrediente_id, n.ingrediente_id) AS ingrediente_id,
             j.cantidad AS cantidad_jsonb,
             n.cantidad AS cantidad_plato_insumo
         FROM hu134_recetas_validas j
                  FULL OUTER JOIN normalizada n
                                  ON n.producto_id = j.producto_id
                                      AND n.ingrediente_id = j.ingrediente_id
         WHERE (
             j.producto_id IS NULL
                 OR n.producto_id IS NULL
                 OR j.cantidad IS DISTINCT FROM n.cantidad
             )
           AND EXISTS (
             SELECT 1
             FROM productos p
             WHERE p.producto_id =
                   COALESCE(j.producto_id, n.producto_id)
               AND p.estado <> 'INACTIVO'
               AND jsonb_typeof(p.ingredientes) = 'array'
               AND jsonb_array_length(p.ingredientes) > 0
         )
           AND EXISTS (
             SELECT 1
             FROM plato_insumo pi
             WHERE pi.plato_id =
                   COALESCE(j.producto_id, n.producto_id)
         )
     )
INSERT INTO auditoria_recetas_hu134 (
    producto_id,
    tipo_evento,
    detalle
)
SELECT
    producto_id,
    'DISCREPANCIA_RECETA',
    jsonb_build_object(
            'ingrediente_id', ingrediente_id,
            'cantidad_jsonb', cantidad_jsonb,
            'cantidad_plato_insumo', cantidad_plato_insumo
    )
FROM diferencias
    ON CONFLICT (producto_id, tipo_evento, detalle) DO NOTHING;

-- 7. Migrar recetas JSONB válidas solo cuando el producto aún no
-- tiene receta normalizada. Si ambas fuentes están pobladas,
-- plato_insumo es la fuente canónica: se conserva y las diferencias
-- ya quedaron registradas en auditoria_recetas_hu134.
-- No se modifica ningún producto INACTIVO.
INSERT INTO plato_insumo (
    plato_id,
    insumo_id,
    cantidad_necesaria
)
SELECT
    r.producto_id,
    r.ingrediente_id,
    r.cantidad
FROM hu134_recetas_validas r
WHERE NOT EXISTS (
    SELECT 1
    FROM plato_insumo existente
    WHERE existente.plato_id = r.producto_id
);

COMMIT;